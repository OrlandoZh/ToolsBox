const CONTROL_LIMITS = Object.freeze({
  itemCount: [0, 100000],
  selectionSize: [0, 10000],
  eventRate: [0, 240],
  domInflation: [0, 8000],
  ioLatencyMS: [0, 800],
  longTaskMS: [0, 250],
  memoryMB: [0, 512],
  listenerLeakRate: [0, 200],
  renderMultiplier: [0, 25],
});

function clamp(value, min, max) {
  return Math.min(max, Math.max(min, value));
}

function normalizeNumber(value, fallback, key) {
  const numberValue = Number(value);
  const finiteValue = Number.isFinite(numberValue) ? numberValue : Number(fallback || 0);
  const limits = CONTROL_LIMITS[key] || [0, Number.MAX_SAFE_INTEGER];
  return Math.round(clamp(finiteValue, limits[0], limits[1]));
}

export function resolveScenario(scenarioId) {
  return SCENARIOS.find((scenario) => scenario.id === scenarioId) || SCENARIOS[0];
}

export function resolveScenarioModule(moduleId) {
  return SCENARIO_MODULES.find((module) => module.id === moduleId) || null;
}

export function listScenariosForModule(moduleId) {
  if (!moduleId || moduleId === "all") {
    return SCENARIOS;
  }
  return SCENARIOS.filter((scenario) => scenario.moduleId === moduleId);
}

export function summarizeScenarioCoverage() {
  const scenarioCount = SCENARIOS.length;
  const sourceReferences = new Set(SCENARIOS.flatMap((scenario) => scenario.sourceReferences || []));
  const routeIds = new Set(SCENARIOS.map((scenario) => scenario.route));
  const modules = SCENARIO_MODULES.map((module) => {
    const scenarios = listScenariosForModule(module.id);
    const gapKinds = new Set(scenarios.map((scenario) => scenario.gapKind || "unspecified"));
    return {
      id: module.id,
      label: module.label,
      summary: module.summary,
      scenarioCount: scenarios.length,
      gapKinds: [...gapKinds].sort(),
      defaultScenarioId: module.defaultScenarioId,
    };
  });
  return {
    scenarioCount,
    moduleCount: SCENARIO_MODULES.length,
    routeCount: routeIds.size,
    sourceReferenceCount: sourceReferences.size,
    modules,
  };
}

export function resolveBottleneckPreset(presetId) {
  return BOTTLENECK_PRESETS.find((preset) => preset.id === presetId) || BOTTLENECK_PRESETS[0];
}

export function applyPresetToScenario(scenarioInput, presetInput, overrides = {}) {
  const scenario = typeof scenarioInput === "string" ? resolveScenario(scenarioInput) : scenarioInput;
  const preset = typeof presetInput === "string" ? resolveBottleneckPreset(presetInput) : presetInput;
  const controls = {};
  NUMBER_KEYS.forEach((key) => {
    const base = scenario?.defaults?.[key] ?? 0;
    const multiplier = preset?.multipliers?.[key] ?? 1;
    controls[key] = normalizeNumber(base * multiplier, base, key);
  });
  Object.entries(overrides || {}).forEach(([key, value]) => {
    if (NUMBER_KEYS.includes(key)) {
      controls[key] = normalizeNumber(value, controls[key], key);
    }
  });
  return controls;
}

export function estimateBottleneckLoad(controls = {}) {
  const normalized = applyPresetToScenario(
    { defaults: Object.fromEntries(NUMBER_KEYS.map((key) => [key, controls[key] ?? 0])) },
    { multipliers: Object.fromEntries(NUMBER_KEYS.map((key) => [key, 1])) },
  );
  const contributors = {
    itemTree: normalized.itemCount * 0.0022 + normalized.selectionSize * 0.07,
    eventStorm: normalized.eventRate * 0.72 + normalized.renderMultiplier * 5.5,
    domPressure: normalized.domInflation * 0.032,
    slowResource: normalized.ioLatencyMS * 0.18,
    longTask: normalized.longTaskMS * 0.95,
    memory: normalized.memoryMB * 0.23 + normalized.listenerLeakRate * 1.8,
  };
  const rawScore = Object.values(contributors).reduce((sum, value) => sum + value, 0);
  const score = clamp(Math.round(rawScore), 0, 100);
  const expectedFPS = clamp(Math.round(60 - score * 0.48 - normalized.longTaskMS * 0.04), 8, 60);
  const expectedLongTasksPerMinute = Math.round((normalized.longTaskMS / 16) * 18 + normalized.eventRate / 18);
  const expectedNodeCount = Math.round(120 + normalized.domInflation + Math.min(normalized.itemCount, 6000) * 0.08);
  const expectedHeapMB = Math.round(18 + normalized.memoryMB + normalized.domInflation * 0.006 + normalized.itemCount * 0.0008);
  return {
    score,
    severity: score >= 82 ? "critical" : score >= 62 ? "high" : score >= 38 ? "medium" : "low",
    expectedFPS,
    expectedLongTasksPerMinute,
    expectedNodeCount,
    expectedHeapMB,
    contributors,
  };
}

export function classifyBottlenecks(estimate) {
  const contributors = estimate?.contributors || {};
  return Object.entries(contributors)
    .map(([id, value]) => ({
      id,
      value: Math.round(value),
      severity: value >= 42 ? "critical" : value >= 28 ? "high" : value >= 14 ? "medium" : "low",
      label: {
        itemTree: "Item Tree / selection 派生成本",
        eventStorm: "事件风暴 / 重复 render",
        domPressure: "DOM 节点膨胀",
        slowResource: "慢 prefs / l10n / stylesheet",
        longTask: "主线程 Long Task",
        memory: "缓存增长 / listener 泄漏",
      }[id] || id,
    }))
    .sort((left, right) => right.value - left.value);
}

export function buildWindTunnelModel({ scenarioId, presetId, overrides } = {}) {
  const scenario = resolveScenario(scenarioId);
  const scenarioModule = resolveScenarioModule(scenario.moduleId);
  const preset = resolveBottleneckPreset(presetId);
  const controls = applyPresetToScenario(scenario, preset, overrides);
  const estimate = estimateBottleneckLoad(controls);
  return {
    id: WIND_TUNNEL_ID,
    scenario,
    scenarioModule,
    preset,
    controls,
    estimate,
    hotZones: classifyBottlenecks(estimate),
    hostSurfaces: scenario.hostSurfaces,
  };
}

export function createSyntheticItems(count, options = {}) {
  const limit = normalizeNumber(count, 0, "itemCount");
  const renderedCount = Math.min(limit, normalizeNumber(options.renderLimit ?? 250, 250, "domInflation"));
  const route = String(options.route || WIND_TUNNEL_ROUTES.LIBRARY);
  return Array.from({ length: renderedCount }, (_, index) => {
    const year = 2020 + (index % 7);
    const selected = index < Number(options.selectionSize || 0);
    return {
      key: `WT${String(index + 1).padStart(5, "0")}`,
      title: `${route === WIND_TUNNEL_ROUTES.READER ? "Reader Sample" : "Library Item"} ${index + 1}`,
      creator: `Template Author ${index % 19}`,
      year,
      type: index % 5 === 0 ? "journalArticle" : index % 3 === 0 ? "bookSection" : "attachment",
      selected,
    };
  });
}

export function createTimelineSample(metrics = {}, now = Date.now()) {
  const fps = Math.round(Number(metrics.fps ?? 60));
  const longTasks = Math.round(Number(metrics.longTasks ?? 0));
  const eventCount = Math.round(Number(metrics.eventCount ?? 0));
  const renderCount = Math.round(Number(metrics.renderCount ?? 0));
  const nodeCount = Math.round(Number(metrics.nodeCount ?? 0));
  const heapMB = Math.round(Number(metrics.heapMB ?? 0));
  const pressure = clamp(Math.round((60 - fps) * 1.2 + longTasks * 4 + heapMB * 0.18 + nodeCount * 0.01), 0, 100);
  return {
    at: new Date(now).toISOString(),
    fps,
    longTasks,
    eventCount,
    renderCount,
    nodeCount,
    heapMB,
    pressure,
  };
}

export function createWindTunnelState(options = {}) {
  const model = buildWindTunnelModel(options);
  return {
    schemaVersion: 1,
    running: false,
    selectedScenarioId: model.scenario.id,
    selectedPresetId: model.preset.id,
    controls: model.controls,
    metrics: {
      fps: model.estimate.expectedFPS,
      longTasks: 0,
      eventCount: 0,
      renderCount: 0,
      nodeCount: model.estimate.expectedNodeCount,
      heapMB: model.estimate.expectedHeapMB,
    },
    timeline: [createTimelineSample({
      fps: model.estimate.expectedFPS,
      longTasks: 0,
      eventCount: 0,
      renderCount: 0,
      nodeCount: model.estimate.expectedNodeCount,
      heapMB: model.estimate.expectedHeapMB,
    })],
  };
}
